/**
 * Unicode Corrigendum #4 changed how five CJK compatibility ideographs normalize, after Unicode 3.2. Mapping them to
 * their Unicode 3.2 forms first makes String.prototype.normalize give the Unicode 3.2 result for every code point
 * Unicode 3.2 assigns.
 */
const UNICODE_32 = new Map([
  [0x2f868, 0x2136a],
  [0x2f874, 0x5f33],
  [0x2f91f, 0x43ab],
  [0x2f95f, 0x7aae],
  [0x2f9bf, 0x4d57],
]);

/** Inclusive [start, end] pairs from a table above, in order. */
function parse(text: string): Uint32Array {
  const items = text.trim().split(/\s+/);
  const out = new Uint32Array(items.length * 2);
  for (let i = 0; i < items.length; i++) {
    const [a, b = a] = items[i].split('-');
    out[2 * i] = Number.parseInt(a, 16);
    out[2 * i + 1] = Number.parseInt(b, 16);
  }
  return out;
}

/** Parsed on the first call. */
let tables: Record<'unassigned' | 'toNothing' | 'toSpace' | 'prohibited' | 'rtl' | 'ltr', Uint32Array> | undefined;

function inTable(table: Uint32Array, cp: number): boolean {
  let lo = 0;
  let hi = table.length / 2;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (table[2 * mid + 1] < cp) lo = mid + 1;
    else hi = mid;
  }
  return lo < table.length / 2 && table[2 * lo] <= cp;
}

/** The code points of a string. A lone surrogate counts as one. */
function codePoints(s: string): number[] {
  return Array.from(s, ch => ch.codePointAt(0) ?? 0);
}

/**
 * Prepares a password as pdf.js does: the same two mappings as SASLprep, then NFKC with the Unicode tables of the
 * running engine. It refuses nothing.
 */
export function pdfjsPrep(input: string): string {
  tables ??= parseTables();
  const t = tables;
  let mapped = '';
  for (const cp of codePoints(input)) {
    if (inTable(t.toSpace, cp)) mapped += ' ';
    else if (!inTable(t.toNothing, cp)) mapped += String.fromCodePoint(cp);
  }
  return mapped.normalize('NFKC');
}

function parseTables(): NonNullable<typeof tables> {
  return {
    unassigned: parse(UNASSIGNED),
    toNothing: parse(TO_NOTHING),
    toSpace: parse(TO_SPACE),
    prohibited: parse(PROHIBITED),
    rtl: parse(RIGHT_TO_LEFT),
    ltr: parse(LEFT_TO_RIGHT),
  };
}

/** Prepares a password with SASLprep, or returns undefined when the profile refuses it. */
export function saslprep(input: string): string | undefined {
  tables ??= parseTables();
  const t = tables;
  let mapped = '';
  for (const cp of codePoints(input)) {
    // A password checked against a stored hash is a stored string, which may not hold unassigned code points. The
    // check runs before normalizing, which uses a later Unicode version and could map them to assigned ones.
    if (inTable(t.unassigned, cp)) return undefined;
    if (inTable(t.toSpace, cp)) mapped += ' ';
    else if (!inTable(t.toNothing, cp)) mapped += String.fromCodePoint(UNICODE_32.get(cp) ?? cp);
  }
  const out = mapped.normalize('NFKC');
  const cps = codePoints(out);
  let rtl = false;
  let ltr = false;
  for (const cp of cps) {
    if (inTable(t.prohibited, cp)) return undefined;
    if (inTable(t.rtl, cp)) rtl = true;
    else if (inTable(t.ltr, cp)) ltr = true;
  }
  // RFC 3454 section 6: right-to-left text holds no left-to-right characters, and starts and ends right to left.
  if (rtl && (ltr || !inTable(t.rtl, cps[0]) || !inTable(t.rtl, cps[cps.length - 1]))) return undefined;
  return out;
}
